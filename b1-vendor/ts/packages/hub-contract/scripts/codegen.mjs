// `npm run codegen`: the TypeScript of the Hub→client contract, from the checked-in JSON Schemas (design section 8, step 2).
//
// Reads  schemas/hub-client/{envelope,pairing,mcp}.schema.json, kinds/*.schema.json, route/*.schema.json, and schemas/ui/*.schema.json.
// Writes src/generated/{hub,route,ui}.ts   the types (json-schema-to-typescript),
//        src/generated/inventory.ts        one list per non-exhaustive set, read from the same schemas,
//        src/generated/registry.ts         errors.json and the kind registry (verbs, actions, effects),
//        src/generated/schemas.ts          the schemas themselves, for the runtime validators.
// A file is written only when its text changes. `npm run codegen -- --check` fails when a file would change.
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const repo = resolve(pkg, "../../..");
const schemasDir = join(repo, "schemas");
const out = join(pkg, "src/generated");
const check = process.argv.includes("--check");

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const jsonFiles = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort();

const banner = "// Generated by scripts/codegen.mjs from the checked-in schemas under schemas/. Do not edit.\n";

/** A non-exhaustive string set is `anyOf: [{ type: string, enum }, { type: string }]` (HC EN-6). TypeScript keeps the names and accepts any other string. */
function openSet(body) {
  const [first, second, ...rest] = body.anyOf ?? [];
  const known = first?.type === "string" && Array.isArray(first.enum) && second?.type === "string" && second.enum === undefined && rest.length === 0;
  return known ? first.enum : null;
}

/** Adds `tsType` to every open set, so the type is `"a" | "b" | (string & {})` and keeps its autocompletion. */
function annotateOpenSets(defs) {
  for (const body of Object.values(defs)) {
    const names = openSet(body);
    if (names) body.tsType = `${names.map((n) => JSON.stringify(n)).join(" | ")} | (string & {})`;
  }
}

/** Merges the `$defs` of several schemas and the root of each (named by its title). A name with two different bodies is an error. */
function merge(files) {
  const defs = {};
  const add = (name, body, from) => {
    if (name in defs && !isDeepStrictEqual(defs[name], body)) {
      throw new Error(`definition ${name} differs between schemas (second: ${from})`);
    }
    defs[name] = body;
  };
  const roots = [];
  for (const [label, schema] of files) {
    const { $defs = {}, $schema, title, ...root } = structuredClone(schema);
    for (const key of Object.keys(root)) if (key.startsWith("x-")) delete root[key];
    for (const [name, body] of Object.entries($defs)) add(name, body, label);
    if (title) {
      add(title, root, label);
      roots.push(title);
    }
  }
  annotateOpenSets(defs);
  return { defs, roots };
}

async function types(label, merged) {
  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: label,
    type: "object",
    additionalProperties: false,
    properties: {},
    $defs: merged.defs,
  };
  let text = await compile(schema, label, {
    bannerComment: banner,
    additionalProperties: false,
    unreachableDefinitions: true,
    declareExternallyReferenced: true,
    strictIndexSignatures: false,
    style: { singleQuote: false, printWidth: 120 },
  });
  // The synthetic root only carries the definitions.
  text = text.replace(new RegExp(`export interface ${label} \\{\\}\\n?`), "");
  return text;
}

const hubFiles = [];
for (const f of ["envelope", "pairing", "mcp"]) hubFiles.push([`hub-client/${f}.schema.json`, read(join(schemasDir, "hub-client", `${f}.schema.json`))]);
const kinds = jsonFiles(join(schemasDir, "hub-client/kinds"));
for (const f of kinds) hubFiles.push([`hub-client/kinds/${f}`, read(join(schemasDir, "hub-client/kinds", f))]);
const routeFiles = jsonFiles(join(schemasDir, "hub-client/route")).map((f) => [`hub-client/route/${f}`, read(join(schemasDir, "hub-client/route", f))]);
const uiFiles = jsonFiles(join(schemasDir, "ui")).map((f) => [`ui/${f}`, read(join(schemasDir, "ui", f))]);

const hub = merge(hubFiles);
const route = merge(routeFiles);
const ui = merge(uiFiles);

/** One list per non-exhaustive string set: the known names, in declaration order (vault: one variant inventory). */
function inventory(defs) {
  const sets = {};
  for (const [name, body] of Object.entries(defs)) {
    const names = openSet(body);
    if (names) sets[name] = names;
  }
  return sets;
}

const errors = read(join(schemasDir, "hub-client/errors.json"));
const kindRegistry = {};
for (const [label, schema] of hubFiles) {
  if (!schema["x-kind"]) continue;
  kindRegistry[schema["x-kind"]] = {
    schema_version: schema["x-schema-version"],
    row: schema.title,
    verbs: schema["x-verbs"],
    actions: schema["x-actions"],
    ...(schema["x-operation-kinds"] ? { operation_kinds: schema["x-operation-kinds"] } : {}),
  };
}

const files = new Map();
files.set("hub.ts", await types("HubContract", hub));
files.set("route.ts", await types("RouteContract", route));
files.set("ui.ts", await types("UiContract", ui));
files.set(
  "inventory.ts",
  `${banner}// Every non-exhaustive string set of the contract and the names that this version knows (HC EN-6, A.2).\n` +
    `export const inventory = ${JSON.stringify(inventory(hub.defs), null, 2)} as const;\n` +
    `export const routeInventory = ${JSON.stringify(inventory(route.defs), null, 2)} as const;\n`,
);
files.set(
  "registry.ts",
  `${banner}// The error registry (HC section 11) and the Hub-owned kind registry (HC section 6, A.7, A.9).\n` +
    `export const errorRegistry = ${JSON.stringify(errors, null, 2)} as const;\n` +
    `export const kindRegistry = ${JSON.stringify(kindRegistry, null, 2)} as const;\n`,
);
const schemaMap = {};
for (const [label, s] of [...hubFiles, ...routeFiles, ...uiFiles]) schemaMap[label] = s;
files.set(
  "schemas.ts",
  `${banner}// The checked-in schemas, keyed by their path under schemas/, for the runtime validators.\n` +
    `export const schemas: Record<string, unknown> = ${JSON.stringify(schemaMap)};\n`,
);

let stale = 0;
mkdirSync(out, { recursive: true });
for (const [name, text] of files) {
  const path = join(out, name);
  const have = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (have === text) continue;
  if (check) {
    console.error(`stale: src/generated/${name}`);
    stale += 1;
  } else {
    writeFileSync(path, text);
  }
}
if (stale > 0) {
  console.error("Run `npm run codegen` in ts/.");
  process.exit(1);
}
console.log(`codegen: ${files.size} file(s) ${check ? "up to date" : "written"}`);
