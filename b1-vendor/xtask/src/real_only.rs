//! `cargo xtask real-only [--check]`: the list of conformance ids that a fake does not prove (design 5.6, rule 7; steward rules R-5, R-7).
//!
//! The list comes from the transcripts: an id marked `"fake": "structural"` runs in full only against a real implementation. The command writes the list between the markers in `README.md`. With `--check` it fails when
//! the README differs from what the transcripts say, so the list cannot drift.

use crate::fsutil::files_under;
use anyhow::{bail, Context, Result};
use serde_json::Value;
use std::collections::BTreeMap;
use std::path::Path;

const BEGIN: &str = "<!-- real-only:begin (generated by `cargo xtask real-only`; do not edit) -->";
const END: &str = "<!-- real-only:end -->";

/// A transcript that is a conformance transcript: not the ledger, and not under `engine-vectors` or `fixtures`.
fn is_transcript(path: &str) -> bool {
    path.starts_with("conformance/")
        && path.ends_with(".json")
        && !path.ends_with("/ledger.json")
        && !path.ends_with("/replacement-map.json")
        && !path.contains("/engine-vectors/")
        && !path.contains("/fixtures/")
}

/// The generated text between the markers, with both marker lines.
pub fn render(root: &Path) -> Result<String> {
    let mut structural: BTreeMap<String, String> = BTreeMap::new();
    for path in files_under(root, &root.join("conformance"))?
        .into_iter()
        .filter(|p| is_transcript(p))
    {
        let text = std::fs::read_to_string(root.join(&path))?;
        let t: Value = serde_json::from_str(&text).with_context(|| format!("parse {path}"))?;
        let id = t["id"].as_str().with_context(|| format!("{path}: no id"))?;
        if t["fake"] == "structural" {
            let ruling = t["ruling"]
                .as_str()
                .with_context(|| format!("{path}: a structural transcript needs a ruling"))?;
            structural.insert(id.to_string(), ruling.to_string());
        }
    }
    let mut out = format!("{BEGIN}\n\n");
    out.push_str("Ids marked `fake: structural`. A fake only checks their stimuli. They run in full against a real implementation, where libghostty is the oracle.\n\n| Id | Ruling |\n|---|---|\n");
    for (id, ruling) in &structural {
        out.push_str(&format!("| `{id}` | {ruling} |\n"));
    }
    out.push_str(&format!("\n{END}"));
    Ok(out)
}

fn splice(readme: &str, block: &str) -> Result<String> {
    let (Some(a), Some(b)) = (readme.find(BEGIN), readme.find(END)) else {
        bail!("README.md has no real-only markers; add `{BEGIN}` and `{END}`");
    };
    Ok(format!(
        "{}{}{}",
        &readme[..a],
        block,
        &readme[b + END.len()..]
    ))
}

pub fn command(root: &Path, args: &[String]) -> Result<()> {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => bail!("usage: cargo xtask real-only [--check]"),
    };
    let path = root.join("README.md");
    let readme = std::fs::read_to_string(&path)?;
    let want = splice(&readme, &render(root)?)?;
    if check {
        if readme != want {
            bail!("README.md real-only list is out of date. Run `cargo xtask real-only`.");
        }
        println!("real-only: README list up to date");
    } else {
        std::fs::write(&path, want)?;
        println!("real-only: README list written");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splice_replaces_only_the_marked_block() {
        let readme = format!("a\n{BEGIN}\nold\n{END}\nb\n");
        let out = splice(&readme, &format!("{BEGIN}\nnew\n{END}")).unwrap();
        assert_eq!(out, format!("a\n{BEGIN}\nnew\n{END}\nb\n"));
    }

    #[test]
    fn a_readme_without_markers_fails() {
        assert!(splice("none", "x").is_err());
    }
}
